"""
Generate content/data/team.tex from content/data/team.json (collect_team.py).

    python scripts/collect_team.py && python scripts/gen_team_table.py

One row per merged pull request and per closed issue would be long; the tables
give counts per student, then every merged PR once with its reviewer verdicts.
"""
import json
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
data = json.loads((BASE / "content/data/team.json").read_text(encoding="utf-8"))
S = {"Kiatisakk": "1005 Kiatisakk", "beambeambeam": "1045 beambeambeam"}


def esc(t):
    for a, b in (("&", r"\&"), ("%", r"\%"), ("_", r"\_"), ("#", r"\#"), ("$", r"\$")):
        t = t.replace(a, b)
    return t


prs = [p for p in data["prs"] if p["author"] in S]
authored = {k: [p for p in prs if p["author"] == k] for k in S}
reviewed = {k: [p for p in prs if k in p["reviews"]] for k in S}
issues = {k: [i for i in data["issues"] if k in i["assignees"]] for k in S}


def verdicts(k):
    appr = sum(1 for p in reviewed[k] if "APPROVED" in p["reviews"][k])
    chg = sum(1 for p in reviewed[k] if "CHANGES_REQUESTED" in p["reviews"][k])
    return appr, chg


L = ["% Generated by scripts/gen_team_table.py from team.json. Do not edit.",
     r"\begin{center}\small",
     r"\begin{tabular}{@{}p{5.2cm}p{5.4cm}p{5.4cm}@{}}",
     r"\toprule & \textbf{67070501005 Kiatisakk} & \textbf{1045 beambeambeam} \\ \midrule"]
L.append("Merged pull requests authored & " + " & ".join(str(len(authored[k])) for k in S) + r" \\")
L.append("Closed issues assigned & " + " & ".join(str(len(issues[k])) for k in S) + r" \\")
L.append("PRs reviewed (teammate's) & " + " & ".join(str(len(reviewed[k])) for k in S) + r" \\")
L.append("\quad with an approval & " + " & ".join(str(verdicts(k)[0]) for k in S) + r" \\")
L.append("\quad with changes requested & " + " & ".join(str(verdicts(k)[1]) for k in S) + r" \\")
L.append("Pull requests, numbers & " + " & ".join(", ".join("\#%d" % p["number"] for p in authored[k]) for k in S) + r" \\")
L.append("Issues, numbers & " + " & ".join(", ".join("\#%d" % i["number"] for i in issues[k]) for k in S) + r" \\")
L.append(r"\bottomrule\end{tabular}\end{center}")
L.append("")
L.append(r"{\footnotesize\begin{longtable}{@{}p{0.9cm}p{8.4cm}p{2.6cm}p{4.3cm}@{}}")
L.append(r"\toprule \textbf{PR} & \textbf{Title} & \textbf{Author} & \textbf{Review by the other student} \\ \midrule \endhead")
for p in data["prs"]:
    if p["author"] not in S:
        continue
    other = [k for k in S if k != p["author"]][0]
    rv = ", ".join(x.lower().replace("_", " ") for x in p["reviews"].get(other, [])) or "none recorded"
    L.append(f"\#{p['number']} & {esc(p['title'])} & {S[p['author']].split()[1]} & {esc(rv)} \\\\")
L.append(r"\bottomrule\end{longtable}}")
(BASE / "content/data/team.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
print("team.tex written;", {k: (len(authored[k]), len(issues[k]), len(reviewed[k])) for k in S})
