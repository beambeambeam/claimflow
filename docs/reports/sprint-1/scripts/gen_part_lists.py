"""
Generate content/part-{a..e}-*.tex, the figure lists of Parts A-E.

Each document starts with a line naming the file and the ref it was captured
from (read from figures/docs/<name>.json, which render_docs.py writes), then
one figure per piece, in order. Pieces come from slice_tall.py (name-p1.png,
...). A document that has not been captured yet becomes a pending box, so the
build never breaks on a missing capture.

    python scripts/gen_part_lists.py

Run it after every recapture: the lists follow what is in figures/docs/.
"""

import json
import re
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
FIG = BASE / "figures" / "docs"
CONTENT = BASE / "content"

PARTS = {
    "part-a-srs":       ("Part A", [("srs", "Software Requirements Specification")]),
    "part-b-features":  ("Part B", [("features", "Feature inventory"),
                                    ("traceability", "Requirements traceability matrix")]),
    "part-c-sds":       ("Part C", [("system-sds", "System-level SDS"),
                                    ("adr-0001", "ADR 0001")]),
    "part-d-plan":      ("Part D", [("plan", "Three-sprint plan")]),
    "part-e-contracts": ("Part E", [("f01", "F-01 contract"), ("f02", "F-02 contract"),
                                    ("f03", "F-03 contract"), ("f04", "F-04 contract"),
                                    ("dod", "Product Definition of Done")]),
}


def pieces(name):
    found = sorted(FIG.glob(f"{name}-p*.png"),
                   key=lambda p: int(re.search(r"-p(\d+)$", p.stem).group(1)))
    if found:
        return [f"figures/docs/{p.name}" for p in found]
    return [f"figures/docs/{name}.png"]


def main():
    for stem, (_part, docs) in PARTS.items():
        lines = [f"% Generated by scripts/gen_part_lists.py. Do not edit.", ""]
        for name, title in docs:
            meta_file = FIG / f"{name}.json"
            if not meta_file.exists():
                lines.append(r"\pending{%s: capture not taken}{\texttt{python scripts/render_docs.py --ref <ref> %s}}"
                             % (title, name))
                continue
            meta = json.loads(meta_file.read_text(encoding="utf-8"))
            lines.append(r"\partsection{%s}{}" % title)
            lines.append(r"\docsource{%s}{%s}{%s}" % (meta["file"], meta["ref"], meta["commit"]))
            if meta.get("problems"):
                lines.append(r"\todo{capture: problems for %s: %s}" % (name, "; ".join(meta["problems"])))
            files = pieces(name)
            for i, f in enumerate(files, 1):
                cap = f"{meta['file']}" + (f", piece {i} of {len(files)}" if len(files) > 1 else "")
                lines.append(r"\evidencepart{%s}{\detokenize{%s}}" % (f, cap))
            lines.append("")
        (CONTENT / f"{stem}.tex").write_text("\n".join(lines), encoding="utf-8")
        print(f"content/{stem}.tex: {sum(1 for l in lines if l.startswith(chr(92) + 'evidencepart'))} figures")


if __name__ == "__main__":
    main()
