// Write <sprint>/build/identity.tex from the student env vars, so names and
// student IDs stay out of git. The preamble inputs it; the build stops when it
// is missing.
//
//   bun run identity 01
//
// Env (docs/reports/.env, loaded by varlock): STUDENT_1_NAME, STUDENT_1_ID,
// STUDENT_2_NAME, STUDENT_2_ID. Student 1 and 2 are the slots One and Two of
// scripts/lib/team.ts.
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

import { tex } from "./lib/latex.ts";
import { loadSprint } from "./lib/sprint.ts";
import { STUDENTS } from "./lib/team.ts";

const sprint = await loadSprint(process.argv[2]);

const need = (key: string) => {
  const value = process.env[key]?.trim();

  if (value === undefined || value === "") {
    throw new Error(`set ${key} in docs/reports/.env (see .env.example)`);
  }

  return value;
};

const lines = [
  "% Generated by scripts/identity.ts from docs/reports/.env. Do not commit.",
];

for (const [i, { slot }] of STUDENTS.entries()) {
  const name = need(`STUDENT_${i + 1}_NAME`);
  const id = need(`STUDENT_${i + 1}_ID`);
  lines.push(
    String.raw`\newcommand{\student${slot}Name}{${tex(name)}}`,
    String.raw`\newcommand{\student${slot}Id}{${tex(id)}}`,
    String.raw`\newcommand{\student${slot}Tag}{${tex(id.slice(-4))}}`
  );
}

mkdirSync(sprint.build, { recursive: true });

const out = path.join(sprint.build, "identity.tex");

writeFileSync(out, `${lines.join("\n")}\n`);

console.log(`${out} written`);
