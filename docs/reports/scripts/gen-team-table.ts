// Generate content/data/team.tex from team.json (collect-team.ts): counts per
// student, then every merged PR once with the other student's review verdicts.
// Student names and IDs stay out of Git: the table prints the identity macros.
//
//   bun run collect-team sprint-1 && bun run gen-team-table sprint-1
import { writeFileSync } from "node:fs";
import path from "node:path";

import { Team, readJson } from "./lib/data.ts";
import { tex } from "./lib/latex.ts";
import { loadSprint } from "./lib/sprint.ts";
import { STUDENTS } from "./lib/team.ts";

const sprint = await loadSprint(process.argv[2]);

const data = readJson(path.join(sprint.data, "team.json"), Team);

const logins: string[] = STUDENTS.map((s) => s.login);
const prs = data.prs.filter((p) => logins.includes(p.author));

const per = STUDENTS.map(({ login }) => {
  const reviewed = prs.filter((p) => login in p.reviews);

  const has = (state: string) =>
    reviewed.filter((p) => p.reviews[login]?.includes(state)).length;

  return {
    approved: has("APPROVED"),
    authored: prs.filter((p) => p.author === login),
    changes: has("CHANGES_REQUESTED"),
    issues: data.issues.filter((i) => i.assignees.includes(login)),
    reviewed,
  };
});

const row = (
  label: string,
  cell: (p: (typeof per)[number]) => string | number
) => `${label} & ${per.map(cell).join(" & ")} \\\\`;

const L = [
  "% Generated by scripts/gen-team-table.ts from team.json. Do not edit.",
  String.raw`\begin{center}\small`,
  String.raw`\begin{tabular}{@{}p{4.8cm}p{5.2cm}p{5.2cm}@{}}`,
  String.raw`\toprule & ${STUDENTS.map((s) => String.raw`\textbf{\student${s.slot}Tag{} ${s.login}}`).join(" & ")} \\ \midrule`,
  row("Merged pull requests authored", (p) => p.authored.length),
  row("Closed issues assigned", (p) => p.issues.length),
  row("PRs reviewed (teammate's)", (p) => p.reviewed.length),
  row(String.raw`\quad with an approval`, (p) => p.approved),
  row(String.raw`\quad with changes requested`, (p) => p.changes),
  row("Pull requests, numbers", (p) =>
    p.authored.map((x) => String.raw`\#${x.number}`).join(", ")
  ),
  row("Issues, numbers", (p) =>
    p.issues.map((x) => String.raw`\#${x.number}`).join(", ")
  ),
  String.raw`\bottomrule\end{tabular}\end{center}`,
  "",
  String.raw`{\footnotesize\begin{longtable}{@{}p{0.9cm}p{7.4cm}p{2.6cm}p{3.9cm}@{}}`,
  String.raw`\toprule \textbf{PR} & \textbf{Title} & \textbf{Author} & \textbf{Review by the other student} \\ \midrule \endhead`,
];

for (const p of prs) {
  const other = logins.find((l) => l !== p.author) ?? "";

  const verdicts =
    (p.reviews[other] ?? [])
      .map((x) => x.toLowerCase().replaceAll("_", " "))
      .join(", ") || "none recorded";

  L.push(
    String.raw`\#${p.number} & ${tex(p.title)} & ${p.author} & ${tex(verdicts)} \\`
  );
}

L.push(String.raw`\bottomrule\end{longtable}}`);

writeFileSync(path.join(sprint.data, "team.tex"), `${L.join("\n")}\n`);

console.log(
  "team.tex written;",
  STUDENTS.map((s, i) => `${s.login}: ${per[i]?.authored.length} PRs`).join(
    ", "
  )
);
