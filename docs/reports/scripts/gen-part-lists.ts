// Generate content/part-{a..e}-*.tex, the figure lists of Parts A-E.
//
// Each document starts with a line naming its file and the ref it was captured
// from (figures/docs/<name>.json, written by render-docs.ts), then one figure
// per piece (slice-tall.ts), then its diagrams at full size
// (capture-diagrams.ts). A document not captured yet becomes a pending box, so
// the build never breaks on a missing capture. Run it after every recapture.
//
//   bun run gen-part-lists 01
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

import { Sidecar, readJson } from "./lib/data.ts";
import type { SidecarMeta } from "./lib/data.ts";
import { size } from "./lib/image.ts";
import { stem } from "./lib/paths.ts";
import { loadSprint } from "./lib/sprint.ts";

const sprint = await loadSprint(process.argv[2]);
const FIG = path.join(sprint.figures, "docs");
const DIAG = path.join(sprint.figures, "diagrams");

// Files named <name>-<n>.png in a folder, ordered by n.
const numbered = (dir: string, name: string, pattern: RegExp) =>
  existsSync(dir)
    ? readdirSync(dir)
        .map((f) => ({ f, n: pattern.exec(stem(f)) }))
        .filter((x) => x.f.startsWith(`${name}-`) && x.n !== null)
        .toSorted((a, b) => Number(a.n?.[1]) - Number(b.n?.[1]))
        .map((x) => x.f)
    : [];

const pieces = (name: string) => {
  const found = numbered(FIG, name, new RegExp(`^${name}-p(\\d+)$`, "u"));

  return found.length > 0
    ? found.map((f) => `figures/docs/${f}`)
    : [`figures/docs/${name}.png`];
};

// The document's diagrams at full size. One more than three times wider than
// tall gets a landscape page.
const diagrams = async (name: string, meta: SidecarMeta) => {
  const shots = numbered(DIAG, name, new RegExp(`^${name}-(\\d+)$`, "u"));

  if (shots.length === 0) {
    return [];
  }

  const out = [
    String.raw`\noindent\textit{The ${shots.length} diagram${shots.length > 1 ? "s" : ""} of \path{${meta.file}}, repeated at full size from the same commit (${meta.commit}):}`,
  ];

  for (const [i, f] of shots.entries()) {
    const { width, height } = await size(path.join(DIAG, f));

    const macro =
      width > 3 * height ? String.raw`\diagramwide` : String.raw`\diagramfull`;

    out.push(
      String.raw`${macro}{figures/diagrams/${f}}{\detokenize{${meta.file}}, diagram ${i + 1} of ${shots.length}}`
    );
  }

  return out;
};

for (const [part, docs] of Object.entries(sprint.config.parts)) {
  const lines = ["% Generated by scripts/gen-part-lists.ts. Do not edit.", ""];

  for (const [name, title] of docs) {
    const metaFile = path.join(FIG, `${name}.json`);

    if (!existsSync(metaFile)) {
      lines.push(
        String.raw`\pending{${title}: capture not taken}{\texttt{bun run render-docs ${sprint.name} --ref <ref> ${name}}}`
      );
      continue;
    }

    const meta = readJson(metaFile, Sidecar);
    lines.push(
      String.raw`\partsection{${title}}{}`,
      String.raw`\docsource{${meta.file}}{${meta.ref}}{${meta.commit}}`
    );

    if (meta.problems.length > 0) {
      lines.push(
        String.raw`\todo{capture: problems for ${name}: ${meta.problems.join("; ")}}`
      );
    }

    const files = pieces(name);

    for (const [i, f] of files.entries()) {
      const cap =
        meta.file +
        (files.length > 1 ? `, piece ${i + 1} of ${files.length}` : "");

      lines.push(String.raw`\evidencepart{${f}}{\detokenize{${cap}}}`);
    }

    lines.push(...(await diagrams(name, meta)), "");
  }

  writeFileSync(path.join(sprint.content, `${part}.tex`), lines.join("\n"));
  const n = lines.filter((l) => l.startsWith(String.raw`\evidencepart`)).length;
  console.log(`content/${part}.tex: ${n} figures`);
}
